/**
 * 超时阈值，集中放一处。
 *
 * 分散在各文件里的话，「这个数字是怎么来的」永远没人答得上来——
 * 而这正是原来那个全局 5 分钟的病根：它不长也不短，它**没有依据**。
 *
 * ## 为什么分成两层
 *
 * 总时长 = 各步骤之和，而**步骤数本身是动态的**：`ask` 的轮数由模型决定
 * （1 轮和 8 轮差 8 倍），`analyze` 的节点由 `plan` 裁剪（跑满 23 秒、
 * 裁剪后 4.9 秒）。给一个方差这么大的分布设固定阈值，必然要么误杀
 * 要么形同虚设——原来那个 5 分钟就同时「偏短」（大仓库跑满真可能超）
 * 和「偏长」（正常情况的 13 倍），两头不讨好。
 *
 * 单步则是同质的：一次模型调用、一次 git 命令，各自的耗时分布稳定得多。
 *
 * 所以职责重新划分：
 *
 * ```
 * 单步超时   真正的超时控制    阈值有依据，定得紧
 * 总时长     兜底回收资源      定得宽，它只是最后一道网
 * ```
 *
 * ## 为什么总时长不能取消
 *
 * 因为**大部分步骤根本打不断**：`getPreEmitDiagnostics`、ts-morph 建图、
 * Tarjan 全是同步 CPU 密集，一旦开始，任何 signal 都停不了它。
 * 总时长不是「更可靠的那道」，而是**那些打不断的操作的唯一防线**。
 */

export const TIMEOUTS = {
  /**
   * 单次模型调用。
   *
   * 实测最慢的一次是 `narrate`（架构解读）18156ms，给 3 倍余量。
   * 超过一分钟基本不是模型慢，是网关把请求吞了——那种情况没有恢复的可能，
   * 早点放手比让用户干等强。
   */
  modelCall: 60_000,

  /**
   * 单条 git 命令。
   *
   * `status` / `diff` / `checkout` 在正常仓库上是毫秒级。十秒意味着
   * `.git/index.lock` 被别的进程占着，或者磁盘卡死——**而且这里是同步
   * 子进程，卡住会把整个 Node 线程钉死，连心跳都发不出去**。
   */
  git: 10_000,

  /**
   * 总时长，按模式分开。三种模式的合理上限差一个数量级，
   * 共用一个值是原来那版最大的问题。
   */
  task: {
    /** 同步部分约 30 秒 + 最多两次模型调用（各 60 秒），约 2 倍余量 */
    analyze: 5 * 60_000,
    /** 8 轮上限 × 每轮 60 秒 = 8 分钟，留出余量 */
    ask: 10 * 60_000,
    /** 两次全量类型检查，大仓库上可能就是几分钟 */
    refactor: 10 * 60_000,
  },
} as const;

/**
 * 把「任务级取消」和「这一步的超时」合成一个信号。
 *
 * 两者都该能中断这次调用，但它们的来源完全不同：前者是用户点了停止，
 * 后者是这一步自己超时了。合成之后调用点只需要关心一个 signal。
 */
export function stepSignal(signal: AbortSignal | undefined, ms: number): AbortSignal {
  const timeout = AbortSignal.timeout(ms);
  return signal ? AbortSignal.any([signal, timeout]) : timeout;
}
