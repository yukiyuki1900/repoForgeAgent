/**
 * 超时阈值，集中放一处。
 *
 * 分散在各文件里的话，「这个数字是怎么来的」永远没人答得上来——
 * 而这正是原来那个全局 5 分钟的病根：它不长也不短，它**没有依据**。
 *
 * ## 为什么分成两层
 *
 * 总时长 = 各步骤之和，而**步骤数本身是动态的**：`ask` 的轮数由模型决定
 * （1 轮和 8 轮差 8 倍），`analyze` 的节点由 `plan` 裁剪（跑满 23 秒、
 * 裁剪后 4.9 秒）。给一个方差这么大的分布设固定阈值，必然要么误杀
 * 要么形同虚设——原来那个 5 分钟就同时「偏短」（大仓库跑满真可能超）
 * 和「偏长」（正常情况的 13 倍），两头不讨好。
 *
 * 单步则是同质的：一次模型调用、一次 git 命令，各自的耗时分布稳定得多。
 *
 * 所以职责重新划分：
 *
 * ```
 * 单步超时   真正的超时控制    阈值有依据，定得紧
 * 总时长     兜底回收资源      定得宽，它只是最后一道网
 * ```
 *
 * ## 为什么总时长不能取消
 *
 * 因为**大部分步骤根本打不断**：`getPreEmitDiagnostics`、ts-morph 建图、
 * Tarjan 全是同步 CPU 密集，一旦开始，任何 signal 都停不了它。
 * 总时长不是「更可靠的那道」，而是**那些打不断的操作的唯一防线**。
 */

export const TIMEOUTS = {
  /**
   * 单次模型调用。
   *
   * 实测最慢的一次是 `narrate`（架构解读）18156ms，给 3 倍余量。
   * 超过一分钟基本不是模型慢，是网关把请求吞了——那种情况没有恢复的可能，
   * 早点放手比让用户干等强。
   */
  modelCall: 60_000,

  /**
   * 单条 git 命令。
   *
   * `status` / `diff` / `checkout` 在正常仓库上是毫秒级。十秒意味着
   * `.git/index.lock` 被别的进程占着，或者磁盘卡死——**而且这里是同步
   * 子进程，卡住会把整个 Node 线程钉死，连心跳都发不出去**。
   */
  git: 10_000,

  /**
   * 总时长，按模式分开。三种模式的合理上限差一个数量级，
   * 共用一个值是原来那版最大的问题。
   *
   * ## 这三个数是推导出来的，不是拍的
   *
   * 既然单步超时已经到位，总时长就有了确定的形式：
   *
   * ```
   * 总时长 = Σ(可打断步骤的上限)  +  Σ(打不断步骤的最坏耗时)  ×  安全系数
   *          ↑ 已经有硬上限，不用估      ↑ 唯一需要估的东西
   * ```
   *
   * 可打断的部分各自有单步超时兜着，上限是确定的。要估的只有同步 CPU
   * 那部分——因为它们**一旦开始就停不下来**。
   *
   * ## 已知数据点（319 文件的 Vue 仓库）
   *
   * ```
   * 全量分析 23 秒 = narrate 18156ms + parseSemantic 4737ms + 其余 8 节点 160ms
   *                   ↑ 可打断          ↑ 打不断，合计约 4.9 秒
   * ```
   *
   * 按支持到 10 倍规模（约 3200 文件）估算。ts-morph 建图不是严格线性的
   * （类型解析有超线性成分），保守按 15 倍算 → **同步部分约 73 秒**。
   *
   * ## 逐模式推导
   *
   * ```
   * analyze   60（narrate 1 次）    + 73  = 133s  × 2  = 266s  → 5 分钟
   * ask       480（8 轮 × 60）      + 73  = 553s        → 10 分钟
   * refactor  0（不调模型）          + 300 = 300s  × 2  = 600s  → 10 分钟
   * ```
   *
   * `ask` 不再乘安全系数：553 秒里 480 秒**已经是硬上限**（8 个 60 秒），
   * 只有 73 秒是估的，对确定的部分再乘 2 是虚胖。
   *
   * ## 上界和下界分别由什么决定
   *
   * **下界**：合法最坏路径的耗时。短于它就误杀正常任务——原来那个全局
   * 五分钟对 `ask` 就是这个毛病（8 轮跑满要 8 分钟）。
   *
   * **上界**：内存。一个 running 任务攥着整个 `CodebaseIndex`
   * （`contents` 是全仓源码，大仓库几十 MB），卡死的任务要占着它直到超时。
   * 单机单用户场景下并发卡死基本是 1–2 个，10 分钟在预算内。
   *
   * **这也是为什么总时长可以定得宽**：它不服务于用户体验，只服务于资源
   * 回收。服务用户体验的是另外两件事——界面上一直有反馈、随时能停。
   * 那两件到位之后，5 分钟还是 10 分钟用户根本感知不到，他早就点停止了。
   *
   * ## 还剩一个不确定性
   *
   * 公式里唯一的未知数是「同步部分随仓库规模怎么增长」，而目前只有
   * 319 文件**一个数据点**，上面那个 15 倍系数是猜的。要消除它得量
   * 三个规模（300 / 1000 / 3000 文件）拟合一下。
   *
   * **改这几个数之前先看公式，不要照着数字改数字。**
   */
  task: {
    /** 60（narrate）+ 73（10 倍规模的同步部分）= 133s，×2 */
    analyze: 5 * 60_000,
    /** 480（8 轮 × 60）+ 73（buildIndex）= 553s */
    ask: 10 * 60_000,
    /** 两次全量类型检查 + 重扫 + git ≈ 300s，×2 */
    refactor: 10 * 60_000,
  },
} as const;

/**
 * 把「任务级取消」和「这一步的超时」合成一个信号。
 *
 * 两者都该能中断这次调用，但它们的来源完全不同：前者是用户点了停止，
 * 后者是这一步自己超时了。合成之后调用点只需要关心一个 signal。
 */
export function stepSignal(signal: AbortSignal | undefined, ms: number): AbortSignal {
  const timeout = AbortSignal.timeout(ms);
  return signal ? AbortSignal.any([signal, timeout]) : timeout;
}
